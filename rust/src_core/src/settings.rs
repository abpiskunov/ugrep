//! Rust-owned settings: the `flag_*`, `color_*` and `match_*` option state that C++ owned in `src/ugrep.cpp`.
//!
//! One `#[repr(C)]` struct, exported as the single symbol `ugrep_settings`. The remaining C++ reads and writes
//! the fields directly through `src/flag.hpp` (plain loads and stores, no call per access). The members that
//! cannot be owned by Rust by value (`std::string`, `std::vector`, `std::set`) stay in `src/settings.cpp`.
//! The field order is mirrored by `Settings` in `src/flag.hpp`; `src/settings.cpp` verifies it at startup
//! against `ugrep_settings_offset`, so a mismatch aborts instead of corrupting state.

