#[no_mangle]
pub extern "C" fn ugrep_settings_size() -> usize {
    std::mem::size_of::<Settings>()
}

#[no_mangle]
pub extern "C" fn ugrep_settings_count() -> usize {
    offsets().len()
}

/// Offset of field `index` (declaration order), or `usize::MAX` if out of range.
#[no_mangle]
pub extern "C" fn ugrep_settings_offset(index: usize) -> usize {
    offsets().get(index).copied().unwrap_or(usize::MAX)
}

#[cfg(test)]
mod tests {
    use super::*;

    const FIELD_COUNT: usize = 156;

    #[test]
    fn layout_is_dense_and_aligned() {
        let o = offsets();
        assert_eq!(o.len(), FIELD_COUNT);
        assert_eq!(ugrep_settings_count(), FIELD_COUNT);
        assert!(o.windows(2).all(|w| w[0] < w[1]));
        assert!(*o.last().unwrap() < ugrep_settings_size());
        assert_eq!(ugrep_settings_size() % std::mem::align_of::<usize>(), 0);
        assert_eq!(ugrep_settings_offset(FIELD_COUNT), usize::MAX);
    }
}
