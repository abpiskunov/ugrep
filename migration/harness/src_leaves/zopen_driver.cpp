// Seam driver for src_leaves.z_open/z_read/z_write/z_close (src/zopen.c through the facade
// src/zopen_facade.cpp): reads zopen seam cases (JSON Lines), runs them and lets the tap
// (CPP2RUST_TAP, CPP2RUST_TAP_OUT) record the facade calls.
//
// Case fields: id; mode (string given to z_open); bits, plain (ints, default 0); input_hex (hex of the
// bytes of the FILE the stream is opened on, default empty); ro (true: the FILE is reopened read-only
// after the bytes were written to it); ops (array of strings, run in order
// on one handle):
//   r:N                 z_read of N bytes
//   ra:CHUNK:LIMIT      z_read of CHUNK bytes until it returns <= 0 or LIMIT calls
//   w:HEX               z_write of the bytes HEX
//   g:KIND:LEN:SEED:CHUNK  z_write of LEN generated bytes (KIND text, rand, zero, ramp) in CHUNK-byte calls
// The handle is closed at the end of the case (z_close) unless z_open returned NULL.
//
// Besides the facade events the driver records, in the same trace schema and in the same order that
// the Rust replay harness reproduces:
//   call/ret  src_leaves.z_file   the bytes of the FILE before the case (setup; not a seam function)
//   state     <fn>, in <fn>       after every facade call: [errno] (errno is cleared before the call)
//   state     z_open|z_close, in same, once at the end: [ftell] or [ftell, "bytes of the FILE"] if the case wrote
// Usage: zopen_driver <cases.jsonl>
#include <cerrno>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <map>
#include <string>
#include <vector>

#include "../../../rust/src_leaves/cpp2rust_tap.hpp"

extern "C" {
void *z_open(FILE *, const char *, int, int);
int z_close(void *);
int z_read(void *, unsigned char *, int);
int z_write(void *, const unsigned char *, int);
}

static std::string parse_string(const std::string& s, size_t& i)
{
  std::string out;
  ++i;
  while (i < s.size() && s[i] != '"')
  {
    if (s[i] == '\\')
    {
      ++i;
      switch (s[i])
      {
        case 'u':
          out += static_cast<char>(std::strtol(s.substr(i + 1, 4).c_str(), nullptr, 16));
          i += 4;
          break;
        case 'n': out += '\n'; break;
        case 't': out += '\t'; break;
        default: out += s[i]; break;
      }
    }
    else
    {
      out += s[i];
    }
    ++i;
  }
  ++i;
  return out;
}

// values: strings, numbers, and arrays of strings (stored as one string per line)
static std::map<std::string, std::string> parse_object(const std::string& s)
{
  std::map<std::string, std::string> m;
  size_t i = 0;
  while (i < s.size())
  {
    if (s[i] != '"')
    {
      ++i;
      continue;
    }
    std::string key = parse_string(s, i);
    while (i < s.size() && (s[i] == ':' || s[i] == ' ')) ++i;
    if (s[i] == '"')
    {
      m[key] = parse_string(s, i);
    }
    else if (s[i] == '[')
    {
      std::string all;
      ++i;
      while (i < s.size() && s[i] != ']')
      {
        if (s[i] == '"')
          all += parse_string(s, i) + "\n";
        else
          ++i;
      }
      ++i;
      m[key] = all;
    }
    else
    {
      size_t j = i;
      while (j < s.size() && s[j] != ',' && s[j] != '}') ++j;
      m[key] = s.substr(i, j - i);
      i = j;
    }
  }
  return m;
}

static std::string from_hex(const std::string& h)
{
  std::string out;
  for (size_t i = 0; i + 1 < h.size(); i += 2)
    out += static_cast<char>(std::strtol(h.substr(i, 2).c_str(), nullptr, 16));
  return out;
}

static std::vector<std::string> split(const std::string& s, char sep)
{
  std::vector<std::string> v;
  size_t p = 0;
  for (;;)
  {
    size_t q = s.find(sep, p);
    v.push_back(s.substr(p, q == std::string::npos ? std::string::npos : q - p));
    if (q == std::string::npos)
      break;
    p = q + 1;
  }
  return v;
}

static std::string generate(const std::string& kind, size_t len, uint32_t seed)
{
  static const char *words[] = { "the ", "quick ", "brown ", "fox ", "jumps ", "over ", "lazy ", "dog ", "ugrep ", "search ", "pattern\n", "file " };
  std::string out;
  uint32_t x = seed * 2654435761u + 12345u;
  auto next = [&x]() { x ^= x << 13; x ^= x >> 17; x ^= x << 5; return x; };
  while (out.size() < len)
  {
    if (kind == "text")
      out += words[next() % 12];
    else if (kind == "rand")
      out += static_cast<char>(next() >> 8);
    else if (kind == "zero")
      out += '\0';
    else
      out += static_cast<char>(out.size());
  }
  out.resize(len);
  return out;
}

static void emit(const char *kind, const std::string& fn, const std::string& fields)
{
  cpp2rust::tap::Sink::get().emit(kind, fn, fields, fn);
}

// errno state right after a facade call
static void after_call(const char *fn, int err)
{
  emit("state", fn, "\"state\":[" + std::to_string(err) + "]");
}

static std::string slurp(FILE *f)
{
  std::string data;
  std::fflush(f);
  std::fseek(f, 0, SEEK_END);
  long n = std::ftell(f);
  std::fseek(f, 0, SEEK_SET);
  data.resize(n > 0 ? static_cast<size_t>(n) : 0);
  if (n > 0 && std::fread(&data[0], 1, data.size(), f) != data.size())
    data.clear();
  return data;
}

static void end_state(const char *fn, FILE *f, bool wrote)
{
  std::fflush(f);
  long pos = std::ftell(f);
  std::string st = "[" + std::to_string(pos);
  if (wrote)
    st += "," + cpp2rust::tap::quote(slurp(f));
  emit("state", fn, "\"state\":" + st + "]");
}

int main(int argc, char **argv)
{
  if (argc != 2)
  {
    std::fprintf(stderr, "usage: zopen_driver cases.jsonl\n");
    return 2;
  }
  std::ifstream in(argv[1], std::ios::binary);
  if (!in)
  {
    std::fprintf(stderr, "cannot open %s\n", argv[1]);
    return 2;
  }
  std::string line;
  while (std::getline(in, line))
  {
    if (line.empty())
      continue;
    auto c = parse_object(line);
    TAP_SET_CASE(c["id"]);
    std::string input = from_hex(c["input_hex"]);
    FILE *file = std::fopen("zopen_case.tmp", "w+b");
    if (!file)
    {
      std::fprintf(stderr, "cannot create zopen_case.tmp\n");
      return 2;
    }
    if (!input.empty())
      std::fwrite(input.data(), 1, input.size(), file);
    std::fflush(file);
    std::fseek(file, 0, SEEK_SET);
    bool ro = c["ro"] == "true";
    if (ro)
    {
      std::fclose(file);
      file = std::fopen("zopen_case.tmp", "rb");
    }
    emit("call", "src_leaves.z_file", "\"args\":[" + cpp2rust::tap::quote(input) + "," + (ro ? "true" : "false") + "]");
    emit("ret", "src_leaves.z_file", "\"ret\":true");

    int bits = std::atoi(c["bits"].c_str());
    int plain = std::atoi(c["plain"].c_str());
    bool wrote = false;
    errno = 0;
    void *z = z_open(file, c["mode"].c_str(), bits, plain);
    after_call("src_leaves.z_open", errno);
    if (z)
    {
      for (const std::string& op : split(c["ops"], '\n'))
      {
        if (op.empty())
          continue;
        std::vector<std::string> a = split(op, ':');
        if (a[0] == "r")
        {
          std::vector<unsigned char> buf(static_cast<size_t>(std::atoi(a[1].c_str())) + 1);
          errno = 0;
          z_read(z, buf.data(), std::atoi(a[1].c_str()));
          after_call("src_leaves.z_read", errno);
        }
        else if (a[0] == "ra")
        {
          int chunk = std::atoi(a[1].c_str());
          std::vector<unsigned char> buf(static_cast<size_t>(chunk) + 1);
          for (int n = std::atoi(a[2].c_str()); n > 0; --n)
          {
            errno = 0;
            int r = z_read(z, buf.data(), chunk);
            after_call("src_leaves.z_read", errno);
            if (r <= 0)
              break;
          }
        }
        else if (a[0] == "w" || a[0] == "g")
        {
          std::string data;
          size_t chunk;
          if (a[0] == "w")
          {
            data = from_hex(a.size() > 1 ? a[1] : "");
            chunk = data.size();
          }
          else
          {
            data = generate(a[1], static_cast<size_t>(std::atol(a[2].c_str())), static_cast<uint32_t>(std::atol(a[3].c_str())));
            chunk = static_cast<size_t>(std::atol(a[4].c_str()));
          }
          wrote = true;
          size_t p = 0;
          do
          {
            size_t n = chunk < data.size() - p ? chunk : data.size() - p;
            errno = 0;
            int r = z_write(z, reinterpret_cast<const unsigned char*>(data.data()) + p, static_cast<int>(n));
            after_call("src_leaves.z_write", errno);
            p += n;
            if (r < 0)
              break;
          } while (p < data.size());
        }
      }
      errno = 0;
      z_close(z);
      after_call("src_leaves.z_close", errno);
      end_state("src_leaves.z_close", file, wrote);
    }
    else
    {
      end_state("src_leaves.z_open", file, wrote);
    }
    std::fclose(file);
  }
  std::remove("zopen_case.tmp");
  return 0;
}
