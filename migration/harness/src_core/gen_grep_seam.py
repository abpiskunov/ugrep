cases = []


def add(cid, args, files=None, env=None):
    files = files if files is not None else {"a.txt": TXT}
    # several files in one run: -J1 keeps the output order deterministic (threads finish in any order)
    if (len(files) > 1 or "missing.txt" in args or ("-" in args and files)) and "-J1" not in args and "-j2" not in args:
        args = ["-J1"] + args
    c = {"id": "gseam-" + cid, "args": args}
    if env:
        c["env"] = env
    c["files"] = files if files is not None else {"a.txt": TXT}
    cases.append(c)


