cases = []


def c(id, args, files=None, stdin=None, env=None):
    # several files or a directory are searched by parallel workers: the output order is deterministic only with
    # --sort (or one thread), so a case that does not test the order asks for it
    multi = sum(1 for a in args if a in ("a.txt", "b.txt", "a.bin", "b.bin", "c.txt", "d.txt", "d", "e", ".")) > 1
    walks = any(a in ("-r", "-R", "d", ".") for a in args) or (not any(a.startswith("-") for a in args[:0]) and "d" in args)
    if (multi or walks) and not any(a.startswith("--sort") or a == "-J1" for a in args):
        args = ["--sort=name"] + args
    d = {"id": id, "args": args}
    if stdin is not None:
        d["stdin"] = stdin
    if env:
        d["env"] = env
    if files:
        d["files"] = files
    cases.append(d)


def plus(files, **more):
    d = dict(files)
    d.update(more)
    return d


